using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;
using Overlink.Vfx;

namespace Overlink.UI
{
    /// <summary>
    /// Button feedback: scale on hover or focus, squash on press, four cyan accent rails, and a
    /// short mask-safe signal shatter on activation. All graphics use standard uGUI materials so they
    /// work inside scroll masks without custom shader stencil properties.
    /// </summary>
    [DisallowMultipleComponent]
    [RequireComponent(typeof(Button))]
    public sealed class UiFxButton : MonoBehaviour, IPointerEnterHandler, IPointerExitHandler,
        IPointerDownHandler, IPointerUpHandler, IPointerClickHandler, ISubmitHandler,
        ISelectHandler, IDeselectHandler
    {
        const float HoverScale = 1.035f;
        const float PressScale = 0.965f;

        RectTransform rect;
        Button button;
        CanvasGroup accents;
        CanvasGroup burst;
        RectTransform[] shards;
        bool hovering;
        bool pressing;
        bool focused;

        /// <summary>Whether hover and focus draw accent rails around the button.</summary>
        public bool ShowAccentRails { get; set; } = true;

        void Awake()
        {
            rect = transform as RectTransform;
            button = GetComponent<Button>();
            // Disable only the overlay generated by the previous effect, never an arbitrary child.
            Transform oldEdge = transform.Find("Edge Flash");
            if (oldEdge != null)
                oldEdge.gameObject.SetActive(false);

            accents = EnsureAccents();
            accents.alpha = 0f;
            burst = EnsureBurst(out shards);
            burst.alpha = 0f;
            burst.gameObject.SetActive(false);
        }

        CanvasGroup EnsureAccents()
        {
            Transform existing = transform.Find("Hover Accents");
            if (existing != null && existing.TryGetComponent(out CanvasGroup group)) return group;

            var root = new GameObject("Hover Accents", typeof(RectTransform), typeof(CanvasGroup));
            root.transform.SetParent(transform, false);
            var bounds = (RectTransform)root.transform;
            bounds.anchorMin = Vector2.zero;
            bounds.anchorMax = Vector2.one;
            bounds.offsetMin = bounds.offsetMax = Vector2.zero;
            var canvasGroup = root.GetComponent<CanvasGroup>();
            canvasGroup.interactable = false;
            canvasGroup.blocksRaycasts = false;
            AddRail(bounds, "Top rail", new Vector2(0f, 1f), new Vector2(0.72f, 1f), new Vector2(0f, -2f), Vector2.zero);
            AddRail(bounds, "Bottom rail", new Vector2(0.28f, 0f), new Vector2(1f, 0f), Vector2.zero, new Vector2(0f, 2f));
            AddRail(bounds, "Left rail", new Vector2(0f, 0.28f), new Vector2(0f, 1f), new Vector2(0f, 0f), new Vector2(2f, 0f));
            AddRail(bounds, "Right rail", new Vector2(1f, 0f), new Vector2(1f, 0.72f), new Vector2(-2f, 0f), new Vector2(0f, 0f));
            return canvasGroup;
        }

        CanvasGroup EnsureBurst(out RectTransform[] result)
        {
            Transform existing = transform.Find("Signal Shatter");
            if (existing != null && existing.TryGetComponent(out CanvasGroup group))
            {
                result = FindShards(existing);
                return group;
            }

            var root = new GameObject("Signal Shatter", typeof(RectTransform), typeof(CanvasGroup));
            root.transform.SetParent(transform, false);
            var bounds = (RectTransform)root.transform;
            bounds.anchorMin = Vector2.zero;
            bounds.anchorMax = Vector2.one;
            bounds.offsetMin = bounds.offsetMax = Vector2.zero;
            var canvasGroup = root.GetComponent<CanvasGroup>();
            canvasGroup.interactable = false;
            canvasGroup.blocksRaycasts = false;

            result = new RectTransform[6];
            Vector2[] directions = { new Vector2(0f, 1f), new Vector2(1f, 0.2f), new Vector2(0.75f, -0.8f),
                new Vector2(-0.8f, -0.7f), new Vector2(-1f, 0.25f), new Vector2(0.35f, 1f) };
            for (int i = 0; i < result.Length; i++)
            {
                var shard = new GameObject("Shard " + i, typeof(RectTransform), typeof(CanvasRenderer), typeof(Image));
                shard.transform.SetParent(root.transform, false);
                var shardRect = (RectTransform)shard.transform;
                shardRect.anchorMin = shardRect.anchorMax = new Vector2(0.5f, 0.5f);
                shardRect.pivot = new Vector2(0.5f, 0.5f);
                shardRect.sizeDelta = new Vector2(i % 2 == 0 ? 3f : 2f, i % 2 == 0 ? 15f : 11f);
                shardRect.localRotation = Quaternion.Euler(0f, 0f, Mathf.Atan2(directions[i].y, directions[i].x) * Mathf.Rad2Deg - 90f);
                var image = shard.GetComponent<Image>();
                image.color = new Color(0.16f, 0.87f, 0.95f, 0.95f);
                image.raycastTarget = false;
                result[i] = shardRect;
            }
            return canvasGroup;
        }

        static RectTransform[] FindShards(Transform root)
        {
            var result = new RectTransform[root.childCount];
            for (int i = 0; i < result.Length; i++) result[i] = root.GetChild(i) as RectTransform;
            return result;
        }

        static void AddRail(Transform parent, string name, Vector2 min, Vector2 max, Vector2 offsetMin, Vector2 offsetMax)
        {
            var rail = new GameObject(name, typeof(RectTransform), typeof(CanvasRenderer), typeof(Image));
            rail.transform.SetParent(parent, false);
            var bounds = (RectTransform)rail.transform;
            bounds.anchorMin = min;
            bounds.anchorMax = max;
            bounds.offsetMin = offsetMin;
            bounds.offsetMax = offsetMax;
            var image = rail.GetComponent<Image>();
            image.color = new Color(0.16f, 0.87f, 0.95f, 0.85f);
            image.raycastTarget = false;
        }

        void UpdateAccents()
        {
            if (accents == null) return;
            float from = accents.alpha;
            float to = ShowAccentRails && button != null && button.IsInteractable() && (hovering || focused) ? 1f : 0f;
            UiTween tween = UiTween.On(accents.transform);
            tween.StopSteps();
            tween.PlayStep(0.16f, UiEase.OutCubic, k =>
            {
                if (accents != null) accents.alpha = Mathf.Lerp(from, to, k);
            });
        }

        public void OnPointerEnter(PointerEventData eventData)
        {
            hovering = true;
            UiTween.On(rect).Play(null, null, Vector3.one * HoverScale, 0.14f, UiEase.OutBack);
            UpdateAccents();
        }

        public void OnPointerExit(PointerEventData eventData)
        {
            hovering = false;
            if (!pressing && !focused) UiTween.On(rect).Play(null, null, Vector3.one, 0.16f, UiEase.OutCubic);
            UpdateAccents();
        }

        public void OnPointerDown(PointerEventData eventData)
        {
            pressing = true;
            UiTween.On(rect).Play(null, null, Vector3.one * PressScale, 0.07f, UiEase.InCubic);
        }

        public void OnPointerUp(PointerEventData eventData)
        {
            pressing = false;
            float target = hovering || focused ? HoverScale : 1f;
            UiTween.On(rect).Play(null, null, Vector3.one * target, 0.18f, UiEase.OutBack);
        }

        public void OnPointerClick(PointerEventData eventData)
        {
            PlaySignalShatter();
        }

        public void OnSubmit(BaseEventData eventData)
        {
            PlaySignalShatter();
        }

        public void OnSelect(BaseEventData eventData)
        {
            focused = true;
            UiTween.On(rect).Play(null, null, Vector3.one * HoverScale, 0.14f, UiEase.OutBack);
            UpdateAccents();
        }

        public void OnDeselect(BaseEventData eventData)
        {
            focused = false;
            if (!hovering && !pressing) UiTween.On(rect).Play(null, null, Vector3.one, 0.16f, UiEase.OutCubic);
            UpdateAccents();
        }

        void PlaySignalShatter()
        {
            if (burst == null || shards == null || !UiVfxGate.Flash) return;

            burst.gameObject.SetActive(true);
            burst.alpha = 1f;
            UiTween burstTween = UiTween.On(burst.transform);
            burstTween.StopSteps();
            burstTween.PlayStep(0.28f, UiEase.OutCubic, k =>
            {
                if (burst != null) burst.alpha = 1f - k;
            }, () =>
            {
                if (burst != null) burst.gameObject.SetActive(false);
            });

            for (int i = 0; i < shards.Length; i++)
            {
                RectTransform shard = shards[i];
                if (shard == null) continue;
                UiTween tween = UiTween.On(shard);
                tween.Stop();
                shard.localPosition = Vector3.zero;
                shard.localScale = Vector3.one;
                Vector2 direction = new Vector2(Mathf.Cos((i * 60f + 90f) * Mathf.Deg2Rad),
                    Mathf.Sin((i * 60f + 90f) * Mathf.Deg2Rad));
                tween.Play((Vector3)(direction * (18f + i * 2f)), null, Vector3.one * 0.18f,
                    0.28f, UiEase.OutCubic);
            }
        }

        void OnDisable()
        {
            hovering = false;
            pressing = false;
            focused = false;
            if (rect != null) rect.localScale = Vector3.one;
            if (accents != null)
            {
                UiTween tween = accents.GetComponent<UiTween>();
                if (tween != null) tween.StopSteps();
                accents.alpha = 0f;
            }
            if (burst != null)
            {
                UiTween tween = burst.GetComponent<UiTween>();
                if (tween != null) tween.Stop();
                burst.alpha = 0f;
                burst.gameObject.SetActive(false);
            }
        }
    }
}
